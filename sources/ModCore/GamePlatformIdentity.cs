namespace ModCore
{
    /// <summary>
    /// Specifies the supported game platform identities.
    /// </summary>
    public enum GamePlatformIdentity
    {
        /// <summary>
        /// Indicates that the value is unknown or not specified.
        /// </summary>
        Unknown = 0,
        /// <summary>
        /// Represents the Steam platform.
        /// </summary>
        Steam = 1,
        /// <summary>
        /// Represents the GOG platform.
        /// </summary>
        GOG = 2
    }
}
