using System.Reflection;
using System.Text.RegularExpressions;
using dc.libs;
using Hashlink.Marshaling;
using Hashlink.Proxy.Clousre;
using ModCore.Modules;

namespace TestRunner
{
    /// <summary>
    /// Verifies exception propagation and stack-trace stitching when a hook
    /// throws across the managed -> Hashlink -> managed call boundary.
    /// </summary>
    public unsafe class HookExceptionTest
    {
        public HookExceptionTest()
        {
            HashlinkMarshal.EnsureThreadRegistered();
        }

        private static double ThrowFromHook(
            Hook__MLib.orig_hMod orig,
            double n,
            double mod)
        {
            throw new InvalidOperationException("hook-boom");
        }

        private sealed class ChainHook
        {
            public bool Throw;
            public int Depth;

            public double Invoke(Hook__MLib.orig_hMod orig, double n, double mod)
            {
                if (Throw)
                {
                    throw new InvalidOperationException($"deep-hook-boom-{Depth}");
                }

                return orig(n, mod);
            }
        }

        private sealed class BoundaryChainHook
        {
            public HashlinkClosure? Next;
            public int Depth;
            public int MaxDepth = 3;

            public double Invoke(Hook__MLib.orig_hMod orig, double n, double mod)
            {
                if (Depth >= MaxDepth)
                {
                    throw new InvalidOperationException("deep-boundary-boom");
                }

                // Explicitly re-enter Hashlink. This is not hook-chain
                // forwarding; each call intentionally creates a new
                // cs -> hl -> cs transition.
                Depth++;
                return (double)Next!.DynamicInvoke(n, mod)!;
            }
        }

        private static InvalidOperationException CaptureHookException()
        {
            var function = HashlinkMarshal.FindFunction("libs.$MLib", "hMod");
            Assert.NotNull(function);

            var hook = new Hook__MLib.hook_hMod(ThrowFromHook);
            var handle = HashlinkHooks.Instance.CreateHook(function, hook);

            try
            {
                var orig = function.CreateClosure().CreateDelegate<Hook__MLib.orig_hMod>();
                return Assert.Throws<InvalidOperationException>(() =>
                {
                    _ = orig(7, 3);
                });
            }
            finally
            {
                handle.Disable();
            }
        }

        [Fact]
        public void HookException_TypeAndMessage_ArePreserved()
        {
            var ex = CaptureHookException();

            Assert.Equal("hook-boom", ex.Message);
            Assert.Null(ex.InnerException);
            Assert.DoesNotContain(nameof(TargetInvocationException), ex.ToString());
        }

        [Fact]
        public void HookException_StackTrace_CrossesManagedAndHashlinkFrames()
        {
            var ex = CaptureHookException();
            var stackTrace = Assert.IsType<string>(ex.StackTrace);

            Assert.Contains(nameof(ThrowFromHook), stackTrace);

            // Boundary frames generated by HlCallbackFactory and
            // HashlinkWrapperFactory respectively.
            Assert.Contains("hl_to_cs+", stackTrace);
            Assert.Contains("cs_to_hl+", stackTrace);

            // ExceptionDispatchInfo is used to rethrow across the native
            // boundary, which produces this separator in .NET stack traces.
            Assert.Contains("--- End of stack trace from previous location ---", stackTrace);
        }

        [Fact]
        public void HookException_MultipleHooks_StayInsideManagedChain()
        {
            var function = HashlinkMarshal.FindFunction("libs.$MLib", "hMod");
            Assert.NotNull(function);

            // Throw hook is added first, so it is the innermost hook.
            // The other two hooks forward through the managed hook chain.
            var throwHook = new ChainHook { Throw = true, Depth = 0 };
            var forward1 = new ChainHook { Depth = 1 };
            var forward2 = new ChainHook { Depth = 2 };

            var handles = new List<HashlinkHooks.HookHandle>
            {
                HashlinkHooks.Instance.CreateHook(
                    function,
                    new Hook__MLib.hook_hMod(throwHook.Invoke)),
                HashlinkHooks.Instance.CreateHook(
                    function,
                    new Hook__MLib.hook_hMod(forward1.Invoke)),
                HashlinkHooks.Instance.CreateHook(
                    function,
                    new Hook__MLib.hook_hMod(forward2.Invoke)),
            };

            try
            {
                var start = function.CreateClosure().CreateDelegate<Hook__MLib.orig_hMod>();
                var ex = Assert.Throws<InvalidOperationException>(() =>
                {
                    _ = start(7, 3);
                });

                Assert.Equal("deep-hook-boom-0", ex.Message);

                var stackTrace = Assert.IsType<string>(ex.StackTrace);
                var csToHlCount = Regex.Matches(stackTrace, Regex.Escape("cs_to_hl+")).Count;
                var hlToCsCount = Regex.Matches(stackTrace, Regex.Escape("hl_to_cs+")).Count;
                var hookFrames = Regex.Matches(
                    stackTrace,
                    Regex.Escape("HookExceptionTest.ChainHook.Invoke")).Count;

                // The hook chain is optimized to forward through managed
                // delegates, so multiple hooks add managed frames but only
                // one cs->hl and one hl->cs transition.
                Assert.Equal(1, csToHlCount);
                Assert.Equal(1, hlToCsCount);
                Assert.True(
                    hookFrames >= 3,
                    $"Expected three hook frames, got {hookFrames}.{Environment.NewLine}{stackTrace}");
                Assert.Contains("--- End of stack trace from previous location ---", stackTrace);
            }
            finally
            {
                foreach (var handle in handles)
                {
                    handle.Disable();
                }
            }
        }

        [Fact]
        public void HookException_ExplicitRecursion_CrossesMultipleBoundaries()
        {
            var function = HashlinkMarshal.FindFunction("libs.$MLib", "hMod");
            Assert.NotNull(function);

            var handler = new BoundaryChainHook
            {
                MaxDepth = 3,
            };
            var hook = new Hook__MLib.hook_hMod(handler.Invoke);
            var handle = HashlinkHooks.Instance.CreateHook(function, hook);

            try
            {
                var closure = function.CreateClosure();
                handler.Next = closure;

                var start = closure.CreateDelegate<Hook__MLib.orig_hMod>();
                var ex = Assert.Throws<InvalidOperationException>(() =>
                {
                    _ = start(7, 3);
                });

                Assert.Equal("deep-boundary-boom", ex.Message);

                var stackTrace = Assert.IsType<string>(ex.StackTrace);
                var csToHlCount = Regex.Matches(stackTrace, Regex.Escape("cs_to_hl+")).Count;
                var hlToCsCount = Regex.Matches(stackTrace, Regex.Escape("hl_to_cs+")).Count;
                var hookFrames = Regex.Matches(
                    stackTrace,
                    Regex.Escape("HookExceptionTest.BoundaryChainHook.Invoke")).Count;

                Assert.True(
                    csToHlCount >= 2 && hlToCsCount >= 2,
                    $"Expected repeated cs<->hl boundary frames, " +
                    $"got cs_to_hl+={csToHlCount}, hl_to_cs+={hlToCsCount}.{Environment.NewLine}{stackTrace}");
                Assert.True(
                    hookFrames >= 2,
                    $"Expected repeated hook frames, got {hookFrames}.{Environment.NewLine}{stackTrace}");
                Assert.Contains("--- End of stack trace from previous location ---", stackTrace);
            }
            finally
            {
                handle.Disable();
            }
        }
    }
}


